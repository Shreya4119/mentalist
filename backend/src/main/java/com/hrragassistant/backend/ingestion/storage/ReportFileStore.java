package com.hrragassistant.backend.ingestion.storage;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.DigestInputStream;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.UUID;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * Keeps uploaded report files on disk instead of in Postgres. Files are
 * streamed in (never fully loaded into memory), named by a random UUID so
 * user-supplied filenames never touch the file system, and hashed on the way
 * in so the same report uploaded twice can be recognised.
 *
 * Configure the folder with app.storage.dir (default ./data/uploads,
 * relative to where the backend is started). A real deployment would put
 * this on S3 or a mounted volume.
 */
@Component
public class ReportFileStore {

    private final Path root;

    public record StoredFile(String relativePath, long sizeBytes, String sha256) {
    }

    public ReportFileStore(@Value("${app.storage.dir:./data/uploads}") String dir) {
        this.root = Path.of(dir).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException e) {
            throw new UncheckedIOException("Could not create the upload folder " + root, e);
        }
    }

    /** Streams {@code in} to a new file; {@code extension} is a safe, lower-case suffix like "pdf". */
    public StoredFile save(InputStream in, String extension) throws IOException {
        String name = UUID.randomUUID() + (extension == null || extension.isBlank() ? "" : "." + extension);
        Path target = root.resolve(name);
        MessageDigest sha = sha256();
        try (DigestInputStream digest = new DigestInputStream(in, sha)) {
            Files.copy(digest, target, StandardCopyOption.REPLACE_EXISTING);
        } catch (IOException e) {
            Files.deleteIfExists(target);
            throw e;
        }
        return new StoredFile(name, Files.size(target), HexFormat.of().formatHex(sha.digest()));
    }

    /** Writes generated bytes (e.g. a PDF built from page photos). */
    public StoredFile save(byte[] bytes, String extension) throws IOException {
        return save(new java.io.ByteArrayInputStream(bytes), extension);
    }

    /** Absolute path of a stored file; refuses anything that would escape the store. */
    public Path resolve(String relativePath) {
        Path p = root.resolve(relativePath).normalize();
        if (!p.startsWith(root)) {
            throw new IllegalArgumentException("Invalid storage path");
        }
        return p;
    }

    public byte[] read(String relativePath) throws IOException {
        return Files.readAllBytes(resolve(relativePath));
    }

    public OutputStream create(String relativePath) throws IOException {
        return Files.newOutputStream(resolve(relativePath));
    }

    public void delete(String relativePath) {
        if (relativePath == null) {
            return;
        }
        try {
            Files.deleteIfExists(resolve(relativePath));
        } catch (IOException | IllegalArgumentException e) {
            // A leftover file is harmless; never fail a delete request over it.
        }
    }

    private static MessageDigest sha256() {
        try {
            return MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
